from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import pandas as pd

from .data import load_study_data
from .folds import make_outer_folds, save_outer_folds, leakage_audit
from .utils import load_json, project_root, save_json, sha256_file


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="configs/confirmatory.json")
    ap.add_argument("--force", action="store_true", help="Replace an existing frozen protocol intentionally")
    args = ap.parse_args()
    root = project_root()
    cfg_path = root / args.config
    cfg = load_json(cfg_path)
    data_path = root / cfg["data_file"]
    d = load_study_data(data_path)

    protocol_dir = root / "protocol"
    protocol_dir.mkdir(exist_ok=True)
    json_path = protocol_dir / "CONFIRMATORY_ANALYSIS_PLAN_v1.json"
    md_path = protocol_dir / "CONFIRMATORY_ANALYSIS_PLAN_v1.md"
    fold_path = protocol_dir / "outer_folds.csv"
    frozen_path = protocol_dir / "FROZEN.sha256"
    if frozen_path.exists() and not args.force:
        raise SystemExit("Protocol already frozen. Use --force only for an intentional versioned change.")

    folds_df = make_outer_folds(d.subjects, n_splits=int(cfg["outer_splits"]))
    save_outer_folds(folds_df, fold_path)
    leakage_audit(folds_df["outer_fold"].to_numpy(), d.subjects)

    plan = {
        "status": "exploratory-informed locked confirmatory analysis",
        "data_sha256": sha256_file(data_path),
        "config_sha256": sha256_file(cfg_path),
        "n_cycles": d.n_cycles,
        "n_subjects": d.n_subjects,
        "age_min": float(pd.Series(d.ages).dropna().min()),
        "age_max": float(pd.Series(d.ages).dropna().max()),
        "outer_cv": f"{cfg['outer_splits']}-fold participant-disjoint GroupKFold",
        "inner_cv": f"{cfg['inner_splits']}-fold grouped CV within each outer-training set",
        "model_selection": "nested: family and hyperparameters selected inside each outer-training fold using the two canonical two-sensor tasks and mean participant RMSE across four kinematic endpoints",
        "families": ["ridge", "histgb", "tcn"],
        "primary_tasks": ["knee_two", "ankle_two"],
        "comparators": ["knee_thigh", "knee_shank", "ankle_shank", "ankle_foot"],
        "augmentation_regimes": cfg["orientation"]["augmentation_regimes"],
        "test_angles_deg": cfg["orientation"]["test_angles_deg"],
        "mc_realizations": cfg["orientation"]["mc_realizations"],
        "clean_tolerance_deg": 4.5,
        "material_clean_degradation_abs_deg": 0.5,
        "material_clean_degradation_rel_pct": 10.0,
        "config": cfg,
    }
    save_json(plan, json_path)
    md = f"""# Locked confirmatory analysis plan v1

This is an exploratory-informed confirmatory analysis. Earlier ExtraTrees/sensor-ranking/robustness results have already been observed.

- Input: `{cfg['data_file']}`
- SHA-256: `{plan['data_sha256']}`
- Cohort: {d.n_cycles} cycles, {d.n_subjects} participants
- Outer validation: {plan['outer_cv']}
- Inner model selection: {plan['inner_cv']}
- Model families: Ridge, HistGradientBoosting, compact TCN
- Model-family selection is nested inside each outer-training fold; outer test subjects are not used for family/hyperparameter choice.
- Primary two-sensor tasks: thigh+shank for knee endpoints; shank+foot for ankle endpoints.
- Test misalignment: {cfg['orientation']['test_angles_deg']} degrees
- Training regimes: {cfg['orientation']['augmentation_regimes']}
- Monte Carlo test realizations per nonzero angle: {cfg['orientation']['mc_realizations']}
- Primary clean tolerance: <=4.5 degrees RMSE per endpoint.
- Material clean penalty: >0.5 degrees or >10% relative RMSE.

Do not edit this file after `FROZEN.sha256` is created. Create v2 for any justified change.
"""
    md_path.write_text(md, encoding="utf-8")

    hash_lines = []
    frozen_inputs = [cfg_path, data_path, json_path, md_path, fold_path]
    frozen_inputs += sorted((root / "src/confirmatory").glob("*.py"))
    for p in frozen_inputs:
        hash_lines.append(f"{sha256_file(p)}  {p.relative_to(root)}")
    frozen_path.write_text("\n".join(hash_lines) + "\n", encoding="utf-8")
    print(f"Frozen protocol written to {protocol_dir}")

if __name__ == "__main__":
    main()
